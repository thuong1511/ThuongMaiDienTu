package com.exed.be.dto.admin;

public class NgheSiRequest {

    private String maNgheSi;
    private String tenNgheSi;
    private String moTa;
    private String ngheNghiep;
    private String linkMXH;

    public String getMaNgheSi() { return maNgheSi; }
    public void setMaNgheSi(String maNgheSi) { this.maNgheSi = maNgheSi; }

    public String getTenNgheSi() { return tenNgheSi; }
    public void setTenNgheSi(String tenNgheSi) { this.tenNgheSi = tenNgheSi; }

    public String getMoTa() { return moTa; }
    public void setMoTa(String moTa) { this.moTa = moTa; }

    public String getNgheNghiep() { return ngheNghiep; }
    public void setNgheNghiep(String ngheNghiep) { this.ngheNghiep = ngheNghiep; }

    public String getLinkMXH() { return linkMXH; }
    public void setLinkMXH(String linkMXH) { this.linkMXH = linkMXH; }
}
